const TABLE_OFFSET: u64 = 8192;
const HDR: usize = 2 * TPKG_SLOT_SIZE; // 560: trailer header start within TRAILER

#[test]
fn encoder_matches_c_implementation_byte_for_byte() {
    let encoded = encode_trailer(&golden_manifest(), TABLE_OFFSET).expect("encode");
    assert_eq!(encoded.len(), TRAILER.len());
    assert_eq!(
        &encoded[..],
        &TRAILER[..],
        "Rust encoder must match the C output exactly"
    );
}

#[test]
fn golden_vector_field_offsets() {
    // Header field positions inside the full trailer (slot table at 0..560).
    assert_eq!(&TRAILER[HDR..HDR + 10], b"TEBAKOTFS\0");
    assert_eq!(&TRAILER[HDR + 10..HDR + 14], &1u32.to_le_bytes()); // version
    assert_eq!(&TRAILER[HDR + 14..HDR + 18], &1u32.to_le_bytes()); // package_flags = LEAN
    assert_eq!(&TRAILER[HDR + 18..HDR + 22], &2u32.to_le_bytes()); // slot_count
    assert_eq!(&TRAILER[HDR + 22..HDR + 30], &8192u64.to_le_bytes()); // table offset
    assert_eq!(
        &TRAILER[HDR + 30..HDR + 30 + 33],
        b"tebako-runtime-0.15.9-linux-arm64"
    );
    assert_eq!(&TRAILER[HDR + 158..HDR + 162], &3u32.to_le_bytes()); // launcher_abi
                                                                     // header_crc32 over header bytes [0, 162) of the header
    let crc = crc32(&TRAILER[HDR..HDR + 162]);
    assert_eq!(&TRAILER[HDR + 162..HDR + 166], &crc.to_le_bytes());
    assert_eq!(crc, 0xBEDC_2824);

    // Slot 0 record.
    assert_eq!(&TRAILER[0..8], &0u64.to_le_bytes()); // offset
    assert_eq!(&TRAILER[8..16], &4778u64.to_le_bytes()); // size
    assert_eq!(&TRAILER[16..20], &TPKG_FORMAT_DWARFS.to_le_bytes());
    assert_eq!(&TRAILER[24..24 + 11], b"/__tebako__");

    // Slot 1 record.
    let s1 = TPKG_SLOT_SIZE;
    assert_eq!(&TRAILER[s1..s1 + 8], &4778u64.to_le_bytes());
    assert_eq!(&TRAILER[s1 + 8..s1 + 16], &1_048_576u64.to_le_bytes());
    assert_eq!(&TRAILER[s1 + 16..s1 + 20], &TPKG_FORMAT_ZIP.to_le_bytes());
    assert_eq!(&TRAILER[s1 + 24..s1 + 24 + 5], b"/data");
}

#[test]
fn parser_reads_c_trailer_back() {
    // Full image = 8192-byte payload + the C-written trailer.
    let mut image = vec![0x5Au8; TABLE_OFFSET as usize];
    image.extend_from_slice(&TRAILER);

    let m = parse_trailer(&image).expect("parse C trailer");
    assert_eq!(m.version, TPKG_VERSION);
    assert_eq!(m.package_flags, TPKG_FLAG_LEAN);
    assert!(m.is_lean());
    assert_eq!(m.launcher_abi, 3);
    assert_eq!(
        m.runtime_ref_str(),
        Some("tebako-runtime-0.15.9-linux-arm64")
    );
    assert_eq!(m.slots.len(), 2);
    assert_eq!(m.slots[0].offset, 0);
    assert_eq!(m.slots[0].size, 4778);
    assert_eq!(m.slots[0].format_id, TPKG_FORMAT_DWARFS);
    assert_eq!(m.slots[0].mount_point_str(), Some("/__tebako__"));
    assert_eq!(m.slots[1].offset, 4778);
    assert_eq!(m.slots[1].size, 1_048_576);
    assert_eq!(m.slots[1].format_id, TPKG_FORMAT_ZIP);
    assert_eq!(m.slots[1].mount_point_str(), Some("/data"));

    // Round trip: re-encoding the parsed manifest reproduces the C bytes.
    let re = encode_trailer(&m, TABLE_OFFSET).expect("re-encode");
    assert_eq!(&re[..], &TRAILER[..]);
}

#[test]
fn crc32_vectors_match_c() {
    // Produced by the C implementation's tpkg_crc32().
    assert_eq!(crc32(b""), 0x0000_0000);
    assert_eq!(crc32(b"123456789"), 0xCBF4_3926); // classic zlib check value
    assert_eq!(crc32(b"tebako"), 0xF39D_4673);
}

// ---------------------------------------------------------------------
// spec 20 §2: format_id 5 = limnifs. The golden vectors above stay
// byte-identical (the C parity); the limnifs allocation EXTENDS them —
// the Rust validation bound admits 5 while the C99 reference keeps
// rejecting it with its named invalid error (fail-closed, correct).
// ---------------------------------------------------------------------

#[test]
fn limnifs_slot_encodes_validates_and_round_trips() {
    let mut m = Manifest {
        version: TPKG_VERSION,
        package_flags: TPKG_FLAG_LEAN,
        launcher_abi: 3,
        ..Default::default()
    };
    m.set_runtime_ref(b"tebako-runtime-0.16.2-linux-arm64");
    m.slots
        .push(Slot::new(0, 4096, TPKG_FORMAT_LIMNIFS, "/__tebako__"));

    // The raised bound admits format 5 (structural validation + the
    // encode gate).
    m.validate().expect("format 5 validates");
    let encoded = encode_trailer(&m, TABLE_OFFSET).expect("encode format 5");

    // The format_id field sits at record offset 16 (little-endian).
    assert_eq!(&encoded[16..20], &TPKG_FORMAT_LIMNIFS.to_le_bytes());

    let mut image = vec![0x5Au8; TABLE_OFFSET as usize];
    image.extend_from_slice(&encoded);
    let parsed = parse_trailer(&image).expect("parse format-5 trailer");
    assert_eq!(parsed, m);
    assert_eq!(parsed.slots[0].format_id, TPKG_FORMAT_LIMNIFS);
}

#[test]
fn format_ids_above_limnifs_stay_unallocated() {
    let mut m = Manifest::default();
    m.slots
        .push(Slot::new(0, 100, TPKG_FORMAT_LIMNIFS + 1, "/m"));
    assert_eq!(m.validate(), Err(TpkgError::Invalid));
    assert_eq!(
        encode_trailer(&m, TABLE_OFFSET),
        Err(TpkgError::Invalid),
        "the encode gate shares the validation bound"
    );
}

#[test]
fn write_to_appends_at_eof_and_read_from_reads_it() {
    use std::io::Cursor;

    let mut image = vec![0x5Au8; TABLE_OFFSET as usize];
    {
        let mut cur = Cursor::new(&mut image);
        write_to(&mut cur, &golden_manifest()).expect("write_to");
    }
    assert_eq!(image.len(), TABLE_OFFSET as usize + TRAILER.len());
    assert_eq!(
        &image[TABLE_OFFSET as usize..],
        &TRAILER[..],
        "appended trailer must equal the C bytes"
    );

    let mut cur = Cursor::new(&image);
    let m = read_from(&mut cur).expect("read_from");
    assert_eq!(m, golden_manifest());
}
