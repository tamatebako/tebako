//! Golden-vector tests: the Rust encoder must reproduce, byte for byte,
//! the trailer written by the reference C implementation
//! (`include/tebako/tpkg.h` in libtfs, compiled with TPKG_IMPLEMENTATION),
//! and the Rust parser must read it back.
//!
//! The vector below was produced by that C implementation (`tpkg_write_fd`)
//! for the manifest in `golden_manifest()` appended to an 8192-byte payload
//! (slot table offset = 8192). Do not "fix" the bytes by hand; regenerate
//! with the C program in docs (see crates/tpkg/tests/README or the commit
//! message that introduced this file).

use tpkg::*;

fn golden_manifest() -> Manifest {
    let mut m = Manifest {
        version: TPKG_VERSION,
        package_flags: TPKG_FLAG_LEAN,
        launcher_abi: 3,
        ..Default::default()
    };
    m.set_runtime_ref(b"tebako-runtime-0.15.9-linux-arm64");
    m.slots
        .push(Slot::new(0, 4778, TPKG_FORMAT_DWARFS, "/__tebako__"));
    m.slots
        .push(Slot::new(4778, 1_048_576, TPKG_FORMAT_ZIP, "/data"));
    m
}

