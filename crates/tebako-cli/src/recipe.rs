//! The graduation path: `tebako press --emit-recipe` renders a feedstock
//! recipe from the press that just SUCCEEDED — engine, requirement, entry,
//! slices, the resolved runtime pair and the one platform leg the press
//! proved. The recipe is generated from working inputs, never rewritten by
//! hand, so a directory press and a feedstock build are the same act at two
//! scales.
//!
//! The document follows the feedstock recipe grammar (`Tebakofile`,
//! spec 13 §9): the top-level identity (`name`/`kind`/`summary`), a `build:`
//! block naming the system that reproduces the press, the `platforms:`
//! matrix, `provides:` and the image axis. Every value is resolved fact —
//! the fields a press cannot prove (other legs, the catalogue identity of a
//! published feedstock) are absent, never guessed.

use std::fs;
use std::path::{Path, PathBuf};

use crate::error::{plain_error, TebakoError};
use crate::options::{PressEngine, PressMode, PressOptions};
use crate::resolve::Resolved;

/// The facts a recipe renders. Built by `press()` AFTER the stitch
/// succeeded: a recipe never describes a press that did not run.
pub struct RecipeInputs<'a> {
    pub opts: &'a PressOptions,
    pub resolved: &'a Resolved,
    /// The pair's language version (node: the resolved node line).
    pub lang_version: &'a str,
    /// The pair's tebako line (the runtime factory's release line).
    pub runtime_tebako: &'a str,
    /// The host platform the press proved, in the product's release-asset
    /// spelling (`macos-arm64`); the recipe renders the spec 03 triplet.
    pub platform: &'a str,
    /// The package file the press wrote; its file name is the payload name.
    pub package: &'a Path,
    /// The in-image entry the payload declares (`/local/<entry>` on the
    /// node arm; the dispatcher's script on the ruby arm).
    pub entry_path: &'a str,
    /// The lockfile the press required and vendored, when the engine has one.
    pub lockfile: Option<String>,
    /// The compose slices the press carried — empty for a plain directory
    /// press.
    pub slices: &'a [(String, Option<String>)],
}

/// Render the recipe for `inputs`. Deterministic: no timestamps, no host
/// paths — the same press inputs render the same bytes.
pub fn render(inputs: &RecipeInputs) -> Result<String, TebakoError> {
    let name = inputs
        .package
        .file_name()
        .map(|s| s.to_string_lossy().into_owned())
        .unwrap_or_else(|| "app".to_string());
    let entry_name = Path::new(inputs.entry_path)
        .file_stem()
        .map(|s| s.to_string_lossy().into_owned())
        .unwrap_or_else(|| name.clone());
    let origin = origin_factory(&inputs.resolved.executable);
    let triplet = triplet(inputs.platform).ok_or_else(|| {
        plain_error(format!(
            "the host platform '{}' maps to no spec 03 triplet — a recipe names platforms in the feedstock grammar, and a guessed triplet would ship a leg nobody proved",
            inputs.platform
        ))
    })?;

    let mut out = String::new();
    out.push_str(&format!("# Feedstock recipe for {name}\n"));
    out.push_str(&format!(
        "# Generated by `tebako press --emit-recipe` (tebako {}) from a press\n# on {}. Every value below is what that press resolved and\n# executed — nothing here is a guess. The platform list names the ONE leg\n# the press proved; add a leg when you prove it.\n",
        env!("CARGO_PKG_VERSION"),
        triplet,
    ));
    out.push_str(&format!("name: \"{}\"\n", q(&name)));
    out.push_str("kind: app\n");
    out.push_str(&format!(
        "summary: \"{}\"\n\n",
        q(&format!("{name} — the pressed app payload"))
    ));

    out.push_str("build:\n");
    out.push_str(
        "  # The press IS the staging engine: each CI leg runs the same press\n  # on that leg's platform, so the feedstock reproduces what the author\n  # tested instead of re-deriving it.\n",
    );
    out.push_str("  system: press\n");
    out.push_str("  press:\n");
    out.push_str("    root: \".\"\n");
    out.push_str(&format!("    entry: \"{}\"\n", q(&inputs.opts.entrance)));
    out.push_str(&format!(
        "    mode: \"{}\"\n",
        mode_preset(inputs.opts.mode)
    ));
    out.push_str(&format!("    format: \"{}\"\n", inputs.opts.format.name()));
    if let Some(lockfile) = &inputs.lockfile {
        out.push_str(&format!("    lockfile: \"{}\"\n", q(lockfile)));
    }
    if inputs.opts.compose.is_some() {
        let compose_name = inputs
            .opts
            .compose
            .as_ref()
            .and_then(|p| p.file_name())
            .map(|s| s.to_string_lossy().into_owned())
            .unwrap_or_else(|| "tebako.yaml".to_string());
        out.push_str(&format!("    compose: \"{}\"\n", q(&compose_name)));
    }
    if !inputs.slices.is_empty() {
        out.push_str("    slices:\n");
        for (slice_name, mount) in inputs.slices {
            out.push_str(&format!("      - name: \"{}\"\n", q(slice_name)));
            if let Some(mount) = mount {
                out.push_str(&format!("        mount: \"{}\"\n", q(mount)));
            }
        }
    }

    out.push_str("  runtime:\n");
    if origin.is_none() {
        out.push_str(
            "    # factory/release: the resolved pair carries no GitHub release\n    # origin marker — name the runtime factory on the feedstock's own CI.\n",
        );
    }
    out.push_str(&format!(
        "    engine: \"{}\"\n",
        inputs.opts.engine.as_str()
    ));
    if let Some(requirement) = requirement(inputs.opts) {
        out.push_str(&format!("    requirement: \"{}\"\n", q(requirement)));
    }
    out.push_str(&format!("    version: \"{}\"\n", q(inputs.lang_version)));
    out.push_str(&format!("    tebako: \"{}\"\n", q(inputs.runtime_tebako)));
    if let Some((factory, release)) = &origin {
        out.push_str(&format!("    factory: \"{}\"\n", q(factory)));
        out.push_str(&format!("    release: \"{}\"\n", q(release)));
    }

    out.push_str(&format!("\nplatforms:\n  - {}\n", triplet));

    out.push_str(&format!(
        "\nprovides:\n  executables:\n    - {{name: \"{}\", path: \"{}\", version: \"0.0.0\"}}\n",
        q(&entry_name),
        q(inputs.entry_path)
    ));
    out.push_str(&format!(
        "\nimage:\n  format: {}\n",
        inputs.opts.format.name()
    ));
    Ok(out)
}

/// Write the rendered recipe to `path`. A recipe this tool generated is
/// rewritten in place (the press may have moved); a document the author
/// wrote (no generated marker) is never clobbered — that is a named error
/// naming both the file and the marker it looked for.
pub fn write(path: &Path, text: &str) -> Result<(), TebakoError> {
    if let Ok(existing) = fs::read_to_string(path) {
        if !existing.starts_with("# Feedstock recipe for ") {
            return Err(plain_error(format!(
                "{} already exists and was not generated by `tebako press --emit-recipe` — write the recipe beside it (--emit-recipe=<path>) and merge it by hand, or delete the file to regenerate",
                path.display()
            )));
        }
    }
    if let Some(parent) = path.parent() {
        if !parent.as_os_str().is_empty() {
            fs::create_dir_all(parent)
                .map_err(|e| plain_error(format!("{e} creating {}", parent.display())))?;
        }
    }
    fs::write(path, text).map_err(|e| plain_error(format!("{e} writing {}", path.display())))
}

/// The default recipe path for a press: `Tebakofile` at the project root
/// (the feedstock repo's own spelling).
pub fn default_path(opts: &PressOptions) -> PathBuf {
    Path::new(opts.root().trim_end_matches(['/', '\\'])).join("Tebakofile")
}

/// The spec 03 triplet for a product release-asset platform name
/// (`macos-arm64` → `aarch64-macos`). The feedstock grammar names legs by
/// triplet, so the recipe translates rather than carrying the product's
/// spelling into a document a feedstock tool reads.
fn triplet(platform: &str) -> Option<&'static str> {
    tpkg::Platform::from_release_asset_name(platform).map(|p| p.as_triplet())
}

/// The engine requirement the project declared, when it declared one.
fn requirement(opts: &PressOptions) -> Option<&str> {
    match opts.engine {
        PressEngine::Node => opts
            .engine_requirement
            .as_deref()
            .filter(|r| !r.trim().is_empty()),
        PressEngine::Ruby => None,
    }
}

/// The spec 23 §13.2 preset name for a press mode (the recipe speaks the
/// current vocabulary, not the deprecated aliases).
fn mode_preset(mode: PressMode) -> &'static str {
    match mode {
        PressMode::Lean => "shared-runtime",
        PressMode::Fat => "self-contained",
        PressMode::Classic => "classic",
        PressMode::Runtime => "runtime",
    }
}

/// The runtime factory and release the resolved pair came from, read from
/// the store's `origin` marker (the provenance the dispatch chain wrote at
/// install time). `None` when the pair carries no marker or the marker is
/// not a GitHub release download URL — the recipe then says so instead of
/// naming a factory nobody verified.
fn origin_factory(exe: &Path) -> Option<(String, String)> {
    let dir = exe.parent()?;
    let origin = fs::read_to_string(dir.join("origin")).ok()?;
    parse_release_origin(origin.trim())
}

/// Parse `https://github.com/<owner>/<repo>/releases/download/<tag>/<asset>`
/// into (`<owner>/<repo>`, `<tag>`). Anything else — a bare release page, a
/// registry URL, an empty marker — is `None`.
pub fn parse_release_origin(url: &str) -> Option<(String, String)> {
    let rest = url
        .strip_prefix("https://github.com/")
        .or_else(|| url.strip_prefix("http://github.com/"))?;
    let parts: Vec<&str> = rest.split('/').collect();
    // owner / repo / releases / download / tag / asset
    if parts.len() < 6 || parts[0].is_empty() || parts[1].is_empty() {
        return None;
    }
    if parts[2] != "releases" || parts[3] != "download" || parts[4].is_empty() {
        return None;
    }
    Some((format!("{}/{}", parts[0], parts[1]), parts[4].to_string()))
}

/// Double-quoted YAML scalar: the grammar's escapes only.
fn q(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Attach the recipe to the press's outcome: write it, say where.
pub fn emit(inputs: &RecipeInputs, path: &Path) -> Result<PathBuf, TebakoError> {
    let text = render(inputs)?;
    write(path, &text)?;
    println!("Wrote feedstock recipe at \"{}\"", path.display());
    Ok(path.to_path_buf())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::options::PressImageFormat;

    fn opts_node() -> PressOptions {
        let mut o = crate::packager::tests::test_opts(false);
        o.root_arg = "/tmp/hello-node".to_string();
        o.entrance = "cli.js".to_string();
        o.output = Some("/tmp/hello-node/cli".to_string());
        o.engine = PressEngine::Node;
        o.engine_requirement = Some(">=20".to_string());
        o.format = PressImageFormat::Limnifs;
        o
    }

    fn inputs<'a>(opts: &'a PressOptions, resolved: &'a Resolved) -> RecipeInputs<'a> {
        RecipeInputs {
            opts,
            resolved,
            lang_version: "24.22.0",
            runtime_tebako: "2.8.55",
            platform: "macos-arm64",
            package: Path::new("/tmp/hello-node/cli"),
            entry_path: "/local/cli.js",
            lockfile: Some("package-lock.json".to_string()),
            slices: &[],
        }
    }

    #[test]
    fn a_node_press_renders_the_feedstock_grammar() {
        let opts = opts_node();
        let resolved = Resolved {
            executable: PathBuf::from(
                "/tmp/nonexistent-pair/tebako-runtime-2.8.55-node-24.22.0-macos-arm64",
            ),
            image: None,
        };
        let text = render(&inputs(&opts, &resolved)).unwrap();
        let doc: serde_yml::Value = serde_yml::from_str(&text).expect("the recipe is YAML");
        assert_eq!(doc["name"], "cli");
        assert_eq!(doc["kind"], "app");
        assert_eq!(doc["build"]["system"], "press");
        assert_eq!(doc["build"]["press"]["entry"], "cli.js");
        assert_eq!(doc["build"]["press"]["mode"], "shared-runtime");
        assert_eq!(doc["build"]["press"]["format"], "limnifs");
        assert_eq!(doc["build"]["press"]["lockfile"], "package-lock.json");
        assert_eq!(doc["build"]["runtime"]["engine"], "node");
        assert_eq!(doc["build"]["runtime"]["requirement"], ">=20");
        assert_eq!(doc["build"]["runtime"]["version"], "24.22.0");
        assert_eq!(doc["build"]["runtime"]["tebako"], "2.8.55");
        // No origin marker on the fabricated pair: the factory is ABSENT,
        // never invented.
        assert!(doc["build"]["runtime"].get("factory").is_none(), "{text}");
        assert!(text.contains("no GitHub release"), "{text}");
        assert_eq!(doc["platforms"][0], "aarch64-macos");
        assert_eq!(doc["provides"]["executables"][0]["name"], "cli");
        assert_eq!(doc["provides"]["executables"][0]["path"], "/local/cli.js");
        assert_eq!(doc["image"]["format"], "limnifs");
    }

    #[test]
    fn the_origin_marker_names_the_factory_and_the_release() {
        let dir = tempfile::tempdir().unwrap();
        let exe = dir
            .path()
            .join("tebako-runtime-2.8.55-node-24.22.0-macos-arm64");
        std::fs::write(&exe, b"stub").unwrap();
        std::fs::write(
            dir.path().join("origin"),
            "https://github.com/tamatebako/tebako-runtime-node/releases/download/v2.8.55/tebako-runtime-2.8.55-node-24.22.0-macos-arm64\n",
        )
        .unwrap();
        let opts = opts_node();
        let resolved = Resolved {
            executable: exe,
            image: None,
        };
        let text = render(&inputs(&opts, &resolved)).unwrap();
        let doc: serde_yml::Value = serde_yml::from_str(&text).unwrap();
        assert_eq!(
            doc["build"]["runtime"]["factory"],
            "tamatebako/tebako-runtime-node"
        );
        assert_eq!(doc["build"]["runtime"]["release"], "v2.8.55");
    }

    #[test]
    fn origin_parsing_is_total_and_strict() {
        assert_eq!(
            parse_release_origin(
                "https://github.com/tamatebako/tebako-runtime-ruby/releases/download/v0.16.32-ruby4.0/x.tfs"
            ),
            Some((
                "tamatebako/tebako-runtime-ruby".to_string(),
                "v0.16.32-ruby4.0".to_string()
            ))
        );
        for not_a_download in [
            "",
            "https://github.com/tamatebako/tebako-runtime-node/releases",
            "https://github.com/tamatebako/tebako-runtime-node/releases/latest",
            "https://github.com/tamatebako",
            "https://gitlab.com/a/b/-/releases/v1/download/x",
            "file:///tmp/pair",
        ] {
            assert_eq!(
                parse_release_origin(not_a_download),
                None,
                "{not_a_download}"
            );
        }
    }

    #[test]
    fn a_preserved_recipe_is_never_clobbered() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("Tebakofile");
        std::fs::write(&path, "name: authored\n").unwrap();
        let err = write(&path, "name: generated\n").unwrap_err();
        assert!(err.message.contains("was not generated"), "{err:?}");
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "name: authored\n");
    }

    #[test]
    fn a_generated_recipe_is_rewritten_in_place() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("Tebakofile");
        write(&path, "# Feedstock recipe for cli\nname: cli\n").unwrap();
        write(&path, "# Feedstock recipe for cli\nname: cli\nversion: 2\n").unwrap();
        assert!(std::fs::read_to_string(&path)
            .unwrap()
            .contains("version: 2"));
    }

    #[test]
    fn compose_slices_ride_the_recipe() {
        let opts = opts_node();
        let resolved = Resolved {
            executable: PathBuf::from("/tmp/nonexistent-pair/x"),
            image: None,
        };
        let slices = vec![
            (
                "flavor-acme".to_string(),
                Some("/flavors.d/flavor-acme".to_string()),
            ),
            ("cache-prime".to_string(), None),
        ];
        let mut i = inputs(&opts, &resolved);
        i.slices = &slices;
        let doc: serde_yml::Value = serde_yml::from_str(&render(&i).unwrap()).unwrap();
        assert_eq!(doc["build"]["press"]["slices"][0]["name"], "flavor-acme");
        assert_eq!(
            doc["build"]["press"]["slices"][0]["mount"],
            "/flavors.d/flavor-acme"
        );
        assert!(doc["build"]["press"]["slices"][1].get("mount").is_none());
    }

    #[test]
    fn the_default_path_is_the_project_roots_tebakofile() {
        let opts = opts_node();
        assert_eq!(
            default_path(&opts),
            PathBuf::from("/tmp/hello-node/Tebakofile")
        );
    }

    #[test]
    fn the_platform_renders_as_a_spec_03_triplet() {
        // The product spells platforms by release asset (macos-arm64);
        // the feedstock grammar spells them by triplet — one translation,
        // never a carried spelling.
        for (asset, triplet) in [
            ("macos-arm64", "aarch64-macos"),
            ("macos-x86_64", "x86_64-macos"),
            ("linux-gnu-x86_64", "x86_64-linux-gnu"),
            ("linux-gnu-arm64", "aarch64-linux-gnu"),
            ("linux-musl-x86_64", "x86_64-linux-musl"),
            ("linux-musl-arm64", "aarch64-linux-musl"),
            ("windows-ucrt64", "x86_64-windows-ucrt"),
            ("windows-ucrt-arm64", "aarch64-windows-ucrt"),
        ] {
            assert_eq!(super::triplet(asset), Some(triplet), "{asset}");
        }
        assert_eq!(super::triplet("aarch64-macos"), None);
    }

    #[test]
    fn an_unmappable_platform_is_a_named_refusal() {
        let opts = opts_node();
        let resolved = Resolved {
            executable: PathBuf::from("/tmp/nonexistent-pair/x"),
            image: None,
        };
        let mut i = inputs(&opts, &resolved);
        i.platform = "plan9-x86_64";
        let err = render(&i).unwrap_err();
        assert!(err.message.contains("no spec 03 triplet"), "{err:?}");
    }
}
